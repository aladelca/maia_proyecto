"""Exercise the deployed API and check all probabilities against the frozen night."""

import argparse
import hashlib
import json
import os
import secrets
import time
import uuid
from pathlib import Path

import boto3
import numpy as np
import pandas as pd
import requests

from sleep_staging.serving.contract import LABELS
from sleep_staging.stack_release import MODEL, RUN_ID, VERSION


def upload(
    client: requests.Session,
    url: str,
    origin: str,
    data: bytes,
    fmt: str,
    model: str | None = None,
) -> dict:
    """Upload a night as the browser does and return the prediction request body."""
    sign = client.post(
        url + "uploads",
        json={
            "size": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "format": fmt,
            **({"model": model} if model else {}),
        },
        timeout=30,
    )
    sign.raise_for_status()
    form = sign.json()
    sent = requests.post(
        form["url"],
        data=form["fields"],
        files={"file": ("night." + fmt, data)},
        timeout=300,
        headers={"Origin": origin},
    )
    if sent.status_code != 201:
        raise RuntimeError(f"Upload failed: HTTP {sent.status_code}")
    return {
        "upload_id": form["upload_id"],
        "version_id": sent.headers["x-amz-version-id"],
    }


def wait(client: requests.Session, url: str, job: str) -> tuple[dict, pd.DataFrame]:
    for _ in range(80):
        status = client.get(url + "predictions/" + job, timeout=20)
        status.raise_for_status()
        data = status.json()
        if data["state"] != "processing":
            break
        time.sleep(2)
    if data["state"] != "succeeded":
        raise RuntimeError(
            f"Prediction {job}: {data['state']} {data.get('reason', '')}"
        )
    reply = requests.get(data["files"]["json"], timeout=25)
    if not reply.ok:
        raise RuntimeError(f"Result download: HTTP {reply.status_code}")
    return data, pd.DataFrame(reply.json()["epochs"])


def verify_edf(
    config: dict, edf: Path, expected_csv: Path, profile: str, model: str = "fullnight"
) -> dict:
    """Compare the selected EDF model with the CSV generated by its local runner."""
    client = requests.Session()
    client.headers.update({"X-Guest-Token": secrets.token_hex(32)})
    url = config["api"] + "/public/v1/"
    started = time.monotonic()
    body = upload(client, url, config["origin"], edf.read_bytes(), "edf", model)
    body.update(format="edf", profile=profile, model=model)
    accepted = client.post(
        url + "predictions",
        headers={"Idempotency-Key": str(uuid.uuid4())},
        json=body,
        timeout=30,
    )
    accepted.raise_for_status()
    data, result = wait(client, url, accepted.json()["job_id"])
    # Hosted epoch IDs carry the job ID, so align the nights by onset.
    result = result.set_index("onset_s")
    expected = pd.read_csv(expected_csv).set_index("onset_s")
    cols = [c for c in expected if c.startswith("prob_")]
    assert result.index.equals(expected.index)
    assert [c for c in result if c.startswith("prob_")] == cols
    assert result.eligible.equals(expected.eligible)
    if model == MODEL:
        assert data["model_version"] == VERSION and data["mlflow_run_id"] == RUN_ID
    if model in ("lightgbm", MODEL):
        assert data["classes"] == LABELS and data["window"] == "full"
    pd.testing.assert_series_equal(
        result.prediction, expected.prediction, check_dtype=False
    )
    np.testing.assert_allclose(
        result[cols],
        expected[cols],
        rtol=0,
        atol=1e-6 if model == "lightgbm" else 1e-5,
        equal_nan=True,
    )
    return {
        "job": data["job_id"],
        "profile": data["profile"],
        "rows": len(result),
        "eligible": data["eligible"],
        "release": data["model_version"],
        "max_difference": float(np.nanmax(abs(result[cols] - expected[cols]))),
        "inference_seconds": data["inference_seconds"],
        "total_seconds": round(time.monotonic() - started, 3),
    }


def check_health(config: dict) -> dict:
    """Fail fast when the API is not ready and report where config.json drifts."""
    ready = requests.get(config["api"] + "/health/ready", timeout=20)
    if ready.status_code != 200:
        raise RuntimeError(f"API not ready: HTTP {ready.status_code} {ready.text}")
    health = requests.get(config["api"] + "/health", timeout=20)
    health.raise_for_status()
    data = health.json()
    advertised = {
        "edf_fullnight": bool(config.get("edfEnabled")),
        "edf_lightgbm": bool(config.get("edfLgbmEnabled")),
    }
    # Informative only: the web may offer a model the backend no longer accepts.
    drift = sorted(k for k, v in advertised.items() if data["features"][k] != v)
    return {
        "version": data["version"],
        "features": data["features"],
        "config_drift": drift,
    }


def verify(config: dict, bundle: Path, *, guest: bool = False) -> dict:
    client = requests.Session()
    url = config["api"] + ("/public/v1/" if guest else "/v1/")
    if guest:
        client.get(url + "examples/default", timeout=20).raise_for_status()
        client.headers.update({"X-Guest-Token": secrets.token_hex(32)})
    else:
        auth = boto3.client("cognito-idp").initiate_auth(
            ClientId=config["clientId"],
            AuthFlow="USER_PASSWORD_AUTH",
            AuthParameters={
                "USERNAME": os.environ["DEMO_USERNAME"],
                "PASSWORD": os.environ["DEMO_PASSWORD"],
            },
        )["AuthenticationResult"]
        if client.get(url + "examples/default", timeout=20).status_code != 401:
            raise RuntimeError("Anonymous request accepted")
        denied = client.get(
            url + "examples/default",
            headers={"Authorization": "Bearer " + auth["IdToken"]},
            timeout=20,
        )
        if denied.status_code not in (401, 403):
            raise RuntimeError("ID token accepted")
        client.headers.update({"Authorization": "Bearer " + auth["AccessToken"]})
    client.get(url + "examples/default", timeout=20).raise_for_status()
    live = client.get(url + "examples/default", timeout=20)
    live.raise_for_status()
    hybrid = live.json().get("model") == MODEL
    if hybrid:
        example = Path("output/demo-sueno-sintetico-10min.edf").read_bytes()
        expected = pd.read_csv("modelos/stack_five/example-expected.csv").set_index(
            "onset_s"
        )
        uploaded = {
            **upload(client, url, config["origin"], example, "edf", MODEL),
            "format": "edf",
            "model": MODEL,
        }
    else:
        example = (bundle / "example.parquet").read_bytes()
        expected = pd.read_parquet(bundle / "expected.parquet").set_index("epoch_id")
        uploaded = upload(client, url, config["origin"], example, "parquet")
    report = {}
    for name, body in [
        ("example", {"example": "default"}),
        ("upload", uploaded),
    ]:
        started = time.monotonic()
        headers = {"Idempotency-Key": str(uuid.uuid4())}
        accepted = client.post(
            url + "predictions", headers=headers, json=body, timeout=30
        )
        accepted.raise_for_status()
        job = accepted.json()["job_id"]
        elapsed = time.monotonic() - started
        if guest:
            other = requests.get(
                url + "predictions/" + job,
                headers={"X-Guest-Token": secrets.token_hex(32)},
                timeout=20,
            )
            assert other.status_code == 404

        data, result = wait(client, url, job)
        if hybrid:
            assert data["model_version"] == VERSION and data["mlflow_run_id"] == RUN_ID
            assert data["classes"] == LABELS
        result = result.set_index("onset_s" if hybrid else "epoch_id")
        cols = ["prob_" + c for c in LABELS]
        assert result.index.equals(expected.index)
        assert result.eligible.equals(expected.eligible)
        pd.testing.assert_series_equal(
            result.prediction, expected.prediction, check_dtype=False
        )
        np.testing.assert_allclose(
            result[cols], expected[cols], rtol=0, atol=1e-6, equal_nan=True
        )
        replay = client.post(
            url + "predictions", headers=headers, json=body, timeout=20
        )
        assert replay.status_code == 202 and replay.json()["job_id"] == job
        if name == "upload":
            assert (
                client.post(
                    url + "predictions",
                    headers=headers,
                    json={"example": "default"},
                    timeout=20,
                ).status_code
                == 409
            )
        report[name] = {
            "job": job,
            "rows": len(result),
            "eligible": data["eligible"],
            "release": data["model_version"],
            "max_difference": float(np.nanmax(abs(result[cols] - expected[cols]))),
            "accept_seconds": round(elapsed, 3),
            "total_seconds": round(time.monotonic() - started, 3),
        }
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--config", type=Path, default=Path("frontend/dist/config.json")
    )
    parser.add_argument("--bundle", type=Path, default=Path("var/cloud/bundle"))
    parser.add_argument(
        "--guest",
        action="store_true",
        help="Test the public API without a Cognito user",
    )
    parser.add_argument(
        "--edf",
        type=Path,
        help="Also upload this EDF as a guest (requires --edf-expected)",
    )
    parser.add_argument(
        "--edf-expected",
        type=Path,
        help="CSV from the selected model’s local runner for the same EDF",
    )
    parser.add_argument(
        "--edf-model", choices=["fullnight", "lightgbm", MODEL], default="fullnight"
    )
    parser.add_argument("--profile", default="auto", help="EDF channel profile")
    parser.add_argument("--require-stack", action="store_true")
    args = parser.parse_args()
    if bool(args.edf) != bool(args.edf_expected):
        parser.error("--edf requires --edf-expected and vice versa")
    config = json.loads(args.config.read_text())
    health = check_health(config)
    report = verify(config, args.bundle, guest=args.guest)
    if args.require_stack and any(row["release"] != VERSION for row in report.values()):
        raise RuntimeError("La release híbrida solicitada no está activa.")
    report["health"] = health
    if args.edf:
        report["edf"] = verify_edf(
            config, args.edf, args.edf_expected, args.profile, args.edf_model
        )
    print(json.dumps(report, indent=2))
